def normalize_branch_id(slug_or_name: str) -> str:
    """Normalize branch input to canonical slug."""
    s = slug_or_name.strip().lower()
    s = s.replace("freshchoice", "").replace("store", "").strip("- _")
    s = re.sub(r"[^a-z0-9]+", "", s)
    return s


def get_branch(branch_identifier: str) -> Optional[dict[str, Any]]:
    """Resolve single branch dictionary by slug or name."""
    clean_id = normalize_branch_id(branch_identifier)
    for b in KNOWN_FRESHCHOICE_STORES:
        if normalize_branch_id(b["id"]) == clean_id or normalize_branch_id(b["name"]) == clean_id:
            return b
    return None


def list_branches(online_only: bool = False) -> list[dict[str, Any]]:
    """Return all branches, optionally filtering for online shopping capable stores."""
    if online_only:
        return [b for b in KNOWN_FRESHCHOICE_STORES if b.get("shopping_online")]
    return list(KNOWN_FRESHCHOICE_STORES)


